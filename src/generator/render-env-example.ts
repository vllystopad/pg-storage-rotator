import type { Profile } from '../config/types.js';

const block = (...lines: string[]): string => [...lines, ''].join('\n');

const header = (profile: Profile): string =>
  block(
    `# Generated by storage:generate for profile ${profile}; do not edit.`,
    '# Copy this file to .env.local, fill in the blanks, then run: npm run storage:generate -- --env .env.local',
  );

const profileBlock = (profile: Profile): string =>
  block(
    '# Where the rotator runs: local | vm | railway.',
    `STORAGE_PROFILE=${profile}`,
    '# true refuses host folders (bind mounts). Windows hosts are always treated as true.',
    `STORAGE_FORBID_BIND_MOUNTS=${profile === 'railway' ? 'true' : 'false'}`,
  );

const databaseBlock = (profile: Profile): string => {
  if (profile === 'railway') {
    return block(
      '# The rotator connects only through this URL. On Railway use the PostgreSQL service connection string.',
      'DATABASE_URL=postgres://postgres:change-me@postgres.railway.internal:5432/railway',
      'PG_MAJOR=18',
    );
  }
  return block(
    '# The rotator connects only through this URL. To use your own database, point it there and start compose',
    '# without --profile demo. With the bundled one, keep the password in step with POSTGRES_PASSWORD.',
    `DATABASE_URL=postgres://postgres:change-me@${profile === 'vm' ? 'db.internal' : 'localhost'}:5432/postgres`,
    'PG_MAJOR=18',
    '',
    '# Bundled PostgreSQL only (--profile demo).',
    'POSTGRES_PASSWORD=change-me',
  );
};

const tiersBlock = (profile: Profile): string => {
  if (profile === 'railway') {
    return block(
      '# Tablespace tiers and a separate WAL volume are not available on railway: Railway gives each service one',
      '# volume. Hot and warm stay in pg_default.',
      'TIER_HOT_DRIVER=default',
      '# TIER_HOT_NAME=',
      '# TIER_HOT_PATH=',
      '# TIER_HOT_HOST_PATH=',
      'TIER_WARM_DRIVER=default',
      '# TIER_WARM_NAME=',
      '# TIER_WARM_PATH=',
      '# TIER_WARM_HOST_PATH=',
      '# PG_WAL_PATH=',
      '# PG_WAL_HOST_PATH=',
    );
  }
  const hostPathNote =
    profile === 'vm'
      ? '# On a VM point this at the attached disk, for example /mnt/disks/pg-warm. Empty means a named volume.'
      : '# Empty means a named volume. A host folder is a bind mount, which is refused on Windows.';
  return block(
    '# Hot: recent partitions. default keeps them in pg_default; tablespace needs a name and a path.',
    'TIER_HOT_DRIVER=default',
    '# TIER_HOT_NAME=',
    '# TIER_HOT_PATH=',
    '# TIER_HOT_HOST_PATH=',
    '',
    '# Warm: older partitions on their own disk. The path is inside the database container.',
    'TIER_WARM_DRIVER=tablespace',
    'TIER_WARM_NAME=warm',
    'TIER_WARM_PATH=/mnt/pg/warm',
    hostPathNote,
    'TIER_WARM_HOST_PATH=',
    '',
    '# WAL on its own volume. Applied only when the data volume is first created.',
    'PG_WAL_PATH=/mnt/pg/wal',
    'PG_WAL_HOST_PATH=',
  );
};

const archiveBlock = (profile: Profile): string =>
  block(
    '# Archive: S3-compatible storage.',
    'TIER_ARCHIVE_DRIVER=s3',
    'TIER_ARCHIVE_BUCKET=pg-archive',
    'TIER_ARCHIVE_PREFIX=',
    profile === 'local'
      ? '# The bundled SeaweedFS. For another provider put its endpoint here; for AWS S3 leave it empty and set S3_REGION.'
      : '# The endpoint your provider shows. For AWS S3 leave it empty and set S3_REGION.',
    `S3_ENDPOINT=${profile === 'local' ? 'http://seaweedfs:8333' : ''}`,
    'S3_REGION=auto',
    profile === 'local'
      ? '# Choose any values: the bundled SeaweedFS adopts them. Elsewhere use the provider keys.'
      : '# The provider keys. Never commit them.',
    'S3_ACCESS_KEY_ID=',
    'S3_SECRET_ACCESS_KEY=',
  );

const policyBlock = (): string =>
  block(
    '# table:interval:hot=N,warm=N,archive=N, separated by semicolons. Ages are cumulative: a partition leaves',
    '# each tier at that age, counted in intervals. Every policy needs an archive tier.',
    'ROTATION_POLICIES=events:month:hot=3,warm=12,archive=36',
    'ROTATION_DRY_RUN=false',
  );

export const renderEnvExample = (profile: Profile): string =>
  [header(profile), profileBlock(profile), databaseBlock(profile), tiersBlock(profile), archiveBlock(profile), policyBlock()].join('\n');
